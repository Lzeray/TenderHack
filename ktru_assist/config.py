def unpack_gz(path: Path) -> Path:
    """Распаковывает `<path>.gz` в `path`, если самого файла нет. Сжатые данные лежат в git (`data/*.gz`),
    чтобы сайт запускался из клона без импорта XML. Запись через временный файл: прерванная распаковка
    не оставляет обрезанную базу."""
    path = Path(path)
    packed = path.with_name(path.name + ".gz")
    if path.exists() or not packed.exists():
        return path
    import gzip
    import shutil
    tmp = path.with_name(path.name + ".unpack")
    with gzip.open(packed, "rb") as src, open(tmp, "wb") as dst:
        shutil.copyfileobj(src, dst, 1 << 20)
    tmp.replace(path)
    return path


def category_for_okpd2(code: str | None) -> str | None:
    if not code:
        return None
    for key, cat in CATEGORIES.items():
        if any(code.startswith(p) for p in cat["okpd2_prefixes"]):
            return key
    return None


